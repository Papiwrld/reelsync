# Secondary locales may use English for provider tips only; these are normal
# keys so every locale carries its own translation.
LOCALES = ("en", "zh", "de", "es", "id", "pt", "ru", "tr", "vi")

for locale in LOCALES:
    path = ROOT / f"{locale}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    translation = data.setdefault("Translation", {})
    added = 0
    for key, value in TRANSLATIONS[locale].items():
        if key not in translation:
            translation[key] = value
            added += 1
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=4) + "\n",
        encoding="utf-8",
    )
    print(f"{locale}: added {added} keys")
